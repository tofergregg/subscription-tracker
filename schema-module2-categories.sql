--   billing_frequency   billing_period                    rename during app wiring
--   usage_rating        rating                            rename during app wiring
--   cost numeric        cost numeric(10,2)                keep numeric(10,2)
--
-- On cost specifically: your existing column is numeric(10,2), which is
-- stricter than the plain numeric you approved. Loosening it would let values
-- like 9.999 into the table and would contradict the MAX_COST ceiling that
-- index.html already enforces. Staying stricter costs you nothing here, so I
-- left it alone rather than widening it. Tell me if you want it widened.
--
-- Also worth correcting: is_active is NOT new in Module 2. It already exists
